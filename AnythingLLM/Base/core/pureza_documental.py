def normalizar_mojibake(texto: str) -> str:
    """
    Normaliza y repara secuencias de mojibake UTF-8 corruptas y elimina
    acentos graves espurios (è, ò, à, ì, ù) que inducen a los LLMs a desviarse
    hacia el catalán o el italiano. Garantiza español técnico puro libre de ruido.
    """
    if not texto:
        return ""

    texto_reparado = texto
    # 1. Reemplazos directos del diccionario de mojibake
    for patron, reemplazo in MOJIBAKE_MAP.items():
        if patron in texto_reparado:
            texto_reparado = texto_reparado.replace(patron, reemplazo)

    # 2. Corrección general de acentos graves a agudos (en español no existen acentos graves)
    # Evita que el LLM confunda texto en español con catalán o italiano
    reemplazos_graves = {
        "à": "á", "è": "é", "ì": "í", "ò": "ó", "ù": "ú",
        "À": "Á", "È": "É", "Ì": "Í", "Ò": "Ó", "Ù": "Ú"
    }
    for grave, agudo in reemplazos_graves.items():
        if grave in texto_reparado:
            texto_reparado = texto_reparado.replace(grave, agudo)

    # 3. Corrección de palabras corruptas o catalanismos comunes inducidos por OCR/ruido
    reemplazos_catalanismos = {
        r"\bperò\b": "pero",
        r"\bamb\b": "con",
        r"\baquest\b": "este",
        r"\baquesta\b": "esta",
        r"\bté\b": "tiene",
        r"\btens de\b": "debes",
        r"\busuaris\b": "usuarios",
        r"\binstal·lació\b": "instalación",
        r"\binstalacio\b": "instalación",
        r"\bconnexió\b": "conexión",
        r"\bconnexio\b": "conexión",
        r"\bdescarrega\b": "descarga",
        r"\bexecuta\b": "ejecuta",
        r"\bcompartís\b": "compartas",
        r"\brevisió\b": "revisión",
        r"\bllicència\b": "licencia",
        r"\bseguretat\b": "seguridad",
        r"\bllora un peu\b": "documentar el fallo y aplicar rollback",
        r"\bllora un poco\b": "documentar el fallo y aplicar rollback",
        r"\breza per que funcioni\b": "verificar dependencias y logs del servicio",
        r"\breza para que funcione\b": "verificar dependencias y logs del servicio",
    }
    for patron_regex, sub_val in reemplazos_catalanismos.items():
        texto_reparado = re.sub(patron_regex, sub_val, texto_reparado, flags=re.IGNORECASE)

    return texto_reparado


